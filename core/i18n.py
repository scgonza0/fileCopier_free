"""Internacionalización simple (es/en) con detección de idioma del sistema.

Uso:
    from core.i18n import T
    label.setText(T("Copy selected files"))   # devuelve el texto en el idioma actual

Detección (current_language()):
    1. env FC_LANG=es|en  (forzado, útil en tests y depuración)
    2. QLocale.system().name()  -> "es_AR"/"en_US" (auto en tiempo de ejecución GUI)
    3. locale.getdefaultlocale()  (fallback sin Qt)
    4. por defecto: "en"

Las claves son el texto en inglés; el diccionario mantiene la versión "es" y "en".
"""
import os
import locale as _locale

SUPPORTED = ("es", "en")


def current_language() -> str:
    forced = os.environ.get("FC_LANG", "").strip().lower()
    if forced in SUPPORTED:
        return forced
    try:
        from PySide6.QtCore import QLocale  # type: ignore
        name = QLocale.system().name().lower()  # ej "es_AR", "en_US"
        if name.startswith("es"):
            return "es"
        if name.startswith("en"):
            return "en"
    except Exception:
        pass
    try:
        sys_loc = (_locale.getdefaultlocale()[0] or "").lower()
        if sys_loc.startswith("es"):
            return "es"
        if sys_loc.startswith("en"):
            return "en"
    except Exception:
        pass
    return "en"


LANG: str = current_language()


def set_language(lang: str) -> None:
    global LANG
    if lang in SUPPORTED:
        LANG = lang


def T(key: str, **fmt) -> str:
    """Traduce `key` (texto en inglés) al idioma actual y aplica .format(**fmt)."""
    table = _STRINGS.get(LANG) or _STRINGS["en"]
    text = table.get(key, _STRINGS["en"].get(key, key))
    if fmt:
        try:
            return text.format(**fmt)
        except Exception:
            return text
    return text


